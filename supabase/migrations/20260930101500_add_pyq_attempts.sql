-- Store each user's PYQ answer attempts.

create table public.pyq_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  pyq_id bigint not null references public.pyqs(id) on delete cascade,
  selected_answer text not null,
  is_correct boolean not null,
  answered_at timestamptz not null default now(),
  unique (user_id, pyq_id)
);

alter table public.pyq_attempts enable row level security;

create policy "Users can read their own PYQ attempts"
on public.pyq_attempts
for select
to authenticated
using (auth.uid() = user_id);

create policy "Users can insert their own PYQ attempts"
on public.pyq_attempts
for insert
to authenticated
with check (auth.uid() = user_id);

create policy "Users can update their own PYQ attempts"
on public.pyq_attempts
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Users can delete their own PYQ attempts"
on public.pyq_attempts
for delete
to authenticated
using (auth.uid() = user_id);
