CREATE TABLE "public"."chapters" (
  "id"          text                     NOT NULL,
  "subject_id"  text                     NOT NULL,
  "title"       text                     NOT NULL,
  "description" text,
  "created_at"  timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT "chapters_pkey" PRIMARY KEY (id)
);

ALTER TABLE "public"."chapters"
  ENABLE ROW LEVEL SECURITY;

CREATE TABLE "public"."subjects" (
  "id"          text                     NOT NULL,
  "name"        text                     NOT NULL,
  "description" text,
  "created_at"  timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT "subjects_pkey" PRIMARY KEY (id)
);

ALTER TABLE "public"."subjects"
  ENABLE ROW LEVEL SECURITY;

CREATE TABLE "public"."topic_progress" (
  "id"                 bigint                   GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "user_id"            uuid                     NOT NULL,
  "topic_id"           text                     NOT NULL,
  "notes_completed"    boolean                  NOT NULL DEFAULT false,
  "videos_completed"   boolean                  NOT NULL DEFAULT false,
  "revision_completed" boolean                  NOT NULL DEFAULT false,
  "pyqs_completed"     boolean                  NOT NULL DEFAULT false,
  "updated_at"         timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT "topic_progress_pkey" PRIMARY KEY (id),
  CONSTRAINT "topic_progress_user_id_topic_id_key" UNIQUE (user_id, topic_id)
);

ALTER TABLE "public"."topic_progress"
  ENABLE ROW LEVEL SECURITY;

CREATE TABLE "public"."topics" (
  "id"                text                     NOT NULL,
  "chapter_id"        text                     NOT NULL,
  "title"             text                     NOT NULL,
  "description"       text,
  "definition"        text,
  "real_life_example" text,
  "notes"             text,
  "revision_points"   jsonb                    NOT NULL DEFAULT '[]'::jsonb,
  "created_at"        timestamp with time zone NOT NULL DEFAULT now(),
  "youtube_videos"    jsonb                    NOT NULL DEFAULT '[]'::jsonb,
  CONSTRAINT "topics_pkey" PRIMARY KEY (id)
);

ALTER TABLE "public"."topics"
  ENABLE ROW LEVEL SECURITY;

ALTER TABLE "public"."chapters"
  ADD CONSTRAINT "chapters_subject_id_fkey" FOREIGN KEY (subject_id) REFERENCES public.subjects(id) ON DELETE CASCADE;

ALTER TABLE "public"."topic_progress"
  ADD CONSTRAINT "topic_progress_user_id_fkey" FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE;

ALTER TABLE "public"."topics"
  ADD CONSTRAINT "topics_chapter_id_fkey" FOREIGN KEY (chapter_id) REFERENCES public.chapters(id) ON DELETE CASCADE;

ALTER TABLE "public"."topic_progress"
  ADD CONSTRAINT "topic_progress_topic_id_fkey" FOREIGN KEY (topic_id) REFERENCES public.topics(id) ON DELETE CASCADE;

CREATE POLICY "Anyone can read chapters" ON "public"."chapters"
  FOR SELECT
  TO "anon", "authenticated"
  USING (true);

CREATE POLICY "Anyone can read subjects" ON "public"."subjects"
  FOR SELECT
  TO "anon", "authenticated"
  USING (true);

CREATE POLICY "Users can insert their own topic progress" ON "public"."topic_progress"
  FOR INSERT
  TO "authenticated"
  WITH CHECK ((auth.uid() = user_id));

CREATE POLICY "Users can read their own topic progress" ON "public"."topic_progress"
  FOR SELECT
  TO "authenticated"
  USING ((auth.uid() = user_id));

CREATE POLICY "Users can update their own topic progress" ON "public"."topic_progress"
  FOR UPDATE
  TO "authenticated"
  USING ((auth.uid() = user_id))
  WITH CHECK ((auth.uid() = user_id));

CREATE POLICY "Anyone can read topics" ON "public"."topics"
  FOR SELECT
  TO "anon", "authenticated"
  USING (true);

